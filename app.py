    if glucose > 140:     risk_factors.append("🟡 High glucose level")
    if bmi > 30:          risk_factors.append("🟡 Obese BMI")
    if smoking_status == "smokes": risk_factors.append("🟡 Current smoker")

    if risk_factors:
        for factor in risk_factors:
            st.write(factor)
