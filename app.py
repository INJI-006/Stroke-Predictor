st.divider()

# ── Input Form ───────────────────────────────────────────────────
col1, col2 = st.columns(2)

with col1:
    gender         = st.selectbox("Gender", ["Male", "Female"])
    age            = st.slider("Age", min_value=1, max_value=82, value=45)
    hypertension   = st.selectbox("Hypertension", [0, 1], format_func=lambda x: "Yes" if x else "No")
    heart_disease  = st.selectbox("Heart Disease", [0, 1], format_func=lambda x: "Yes" if x else "No")
    ever_married   = st.selectbox("Ever Married", ["Yes", "No"])

with col2:
    work_type      = st.selectbox("Work Type", ["Private", "Self-employed", "Govt_job", "children", "Never_worked"])
    residence_type = st.selectbox("Residence Type", ["Urban", "Rural"])
    glucose        = st.slider("Avg Glucose Level", min_value=55.0, max_value=272.0, value=100.0)
    bmi            = st.slider("BMI", min_value=10.0, max_value=98.0, value=25.0)
    smoking_status = st.selectbox("Smoking Status", ["never smoked", "formerly smoked", "smokes", "Unknown"])

st.divider()

# ── Prediction Button ────────────────────────────────────────────
if st.button("🔍 Predict Stroke Risk", use_container_width=True):

    # Package raw user input into a dict matching training columns
    user_data = {
        'gender':            gender,
        'age':               age,
        'hypertension':      hypertension,
        'heart_disease':     heart_disease,
        'ever_married':      ever_married,
        'work_type':         work_type,
        'Residence_type':    residence_type,
        'avg_glucose_level': glucose,
        'bmi':               bmi,
        'smoking_status':    smoking_status
    }

    # Preprocess and predict
    processed    = preprocess_input(user_data)
    prediction   = model.predict(processed)[0]           # 0 or 1
    probability  = model.predict_proba(processed)[0][1]  # probability of stroke

    # ── Display Result ───────────────────────────────────────────
    st.subheader("Prediction Result")

    if prediction == 1:
        st.error(f"⚠️ High Stroke Risk Detected")
        st.metric("Stroke Probability", f"{probability*100:.1f}%")
        st.warning("This patient shows elevated stroke risk. Please consult a medical professional.")
    else:
        st.success(f"✅ Low Stroke Risk")
        st.metric("Stroke Probability", f"{probability*100:.1f}%")
        st.info("No immediate stroke risk detected based on the provided data.")

    # ── Risk Factor Summary ──────────────────────────────────────
    st.subheader("Patient Risk Summary")

    risk_factors = []
    if age > 50:          risk_factors.append("🔴 Age over 50")
