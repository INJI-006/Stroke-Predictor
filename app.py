import streamlit as st
import joblib
import numpy as np
import pandas as pd
from sklearn.preprocessing import LabelEncoder

# ── Page Configuration ──────────────────────────────────────────
st.set_page_config(
    page_title="Stroke Risk Predictor",
    page_icon="🧠",
    layout="centered"
)

# ── Load saved model and transformers ───────────────────────────
@st.cache_resource
def load_artifacts():
    """Loads the trained model, scaler, and feature selector from disk."""
    model    = joblib.load('stroke_model.pkl')
    scaler   = joblib.load('scaler.pkl')
    selector = joblib.load('selector.pkl')
    return model, scaler, selector

model, scaler, selector = load_artifacts()

# ── Helper Functions ─────────────────────────────────────────────
def get_bmi_category(bmi):
    """Converts raw BMI value into a category label."""
    if bmi < 18.5:   return 'Underweight'
    elif bmi < 25:   return 'Normal'
    elif bmi < 30:   return 'Overweight'
    else:            return 'Obese'

def get_age_group(age):
    """Converts raw age into a life stage group label."""
    if age < 18:     return 'Minor'
    elif age < 40:   return 'Young Adult'
    elif age < 60:   return 'Middle Aged'
    else:            return 'Senior'

def encode_input(raw_input_df):
    """
    Applies label encoding to categorical columns.
    Uses the same encoding logic as the training pipeline.

    Parameters:
        raw_input_df : DataFrame with one row of raw user input
    Returns:
        Encoded DataFrame ready for scaling and selection
    """
    le = LabelEncoder()
    df = raw_input_df.copy()
    cat_cols = df.select_dtypes(include='object').columns
    for col in cat_cols:
        df[col] = le.fit_transform(df[col])
    return df

def preprocess_input(user_data):
    """
    Full preprocessing pipeline: encode → scale → select features.

    Parameters:
        user_data : dict of raw values from the user
    Returns:
        Preprocessed numpy array ready for model prediction
    """
    # Build base DataFrame
    df = pd.DataFrame([user_data])

    # Add engineered features
    df['bmi_category'] = df['bmi'].apply(get_bmi_category)
    df['age_group']    = df['age'].apply(get_age_group)
    df['risk_score']   = (
        df['hypertension'] +
        df['heart_disease'] +
        (df['age'] > 50).astype(int)
    )

    # Drop id (not a feature)
    df['age'] = df['age'].astype(int)

    # Encode categorical columns
    df_encoded = encode_input(df)

    # Scale using saved scaler
    df_scaled = pd.DataFrame(
        scaler.transform(df_encoded),
        columns=df_encoded.columns
    )

    # Select features using saved selector
    df_selected = df_scaled[df_scaled.columns[selector.get_support()]]

    return df_selected.values

# ── UI Layout ────────────────────────────────────────────────────
st.title("🧠 Stroke Risk Predictor")
